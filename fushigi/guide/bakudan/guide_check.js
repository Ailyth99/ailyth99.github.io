let curLang = localStorage.getItem('bh_lang') || 'both';
function setLang(l){
  curLang = l;
  document.body.classList.remove('lang-ja','lang-zh');
  if(l==='ja') document.body.classList.add('lang-ja');
  if(l==='zh') document.body.classList.add('lang-zh');
  localStorage.setItem('bh_lang', l);
  document.querySelectorAll('.langbar button').forEach(b=>b.classList.toggle('active', b.dataset.lang===l));
}
setLang(curLang);

