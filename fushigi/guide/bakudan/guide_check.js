function renderRoute(){
  // 隐藏角色若因取消通关而重新上锁，自动切回第一个角色
  if(routes[activeRoute].hidden && !isHiddenUnlocked()) activeRoute = 0;
  renderTabs();
  const r=routes[activeRoute]; renderSide(r); renderMain(r);
}
function selectRoute(i){ activeRoute=i; renderRoute(); document.getElementById('routes').scrollIntoView({behavior:'smooth',block:'start'}); }
function jumpChap(e,ri,ci){ e.preventDefault(); const el=document.getElementById(`chap-${ri}-${ci}`); if(el) el.scrollIntoView({behavior:'smooth',block:'start'}); }
function jumpTop(e){ e.preventDefault(); document.getElementById('chap-top').scrollIntoView({behavior:'smooth',block:'start'}); }
function jumpBadEnd(e){ e.preventDefault(); document.getElementById('chap-badend').scrollIntoView({behavior:'smooth',block:'start'}); }

// 勾选选项
function toggleStep(name, gi, checked){
  if(!stepState[name]) stepState[name]=[];
  const arr = stepState[name];
  const pos = arr.indexOf(gi);
  if(checked && pos<0) arr.push(gi);
  if(!checked && pos>=0) arr.splice(pos,1);
  localStorage.setItem('bh_step_state', JSON.stringify(stepState));
  // 局部刷新左栏进度 + 右栏头部，不重绘整个列表（保持勾选焦点）
  const r = routes.find(x=>x.name===name);
  const total = totalSteps(r), doneN = doneSteps(r,name), pct = total?Math.round(doneN/total*100):0;
  const row = document.getElementById(`step-${activeRoute}-${gi}`);
  if(row) row.classList.toggle('checked', checked);
  const hp = mainEl.querySelector('.rt-chap-progress');
  if(hp) hp.innerHTML = `<b>${pct}%</b> · ${doneN}/${total} 项`;
  // 更新对应章的计数 + 左栏目录百分比
  renderSide(r);
  const ci = chapIndexOf(r, gi);
  const head = document.getElementById(`chap-${activeRoute}-${ci}`);
  if(head){
    const c = r.chs[ci], start = chapStart(r,ci);
    let cDone=0; (stepState[name]||[]).forEach(i=>{ if(i>=start && i<start+c.opts.length) cDone++; });
    const cnt = head.querySelector('.rt-chap-head span:last-child');
    if(cnt) cnt.textContent = `${cDone}/${c.opts.length}`;
  }
}
function chapStart(r,ci){ let s=0; for(let k=0;k<ci;k++) s+=r.chs[k].opts.length; return s; }
function chapIndexOf(r,gi){ let s=0; for(let k=0;k<r.chs.length;k++){ const e=s+r.chs[k].opts.length; if(gi<e) return k; s=e; } return 0; }

// 标记通关（保留与顶部进度条联动）
function toggleRoute(name){
  const btn = sideEl.querySelector('.rt-done-btn');
  if(doneSet.has(name)){
    doneSet.delete(name); if(btn){btn.classList.remove('done');btn.textContent='标记通关';}
  } else {
    doneSet.add(name); if(btn){btn.classList.add('done');btn.textContent='✓ 已通关';}
  }
  localStorage.setItem('bh_route_done', JSON.stringify([...doneSet]));
  updateRouteProgress();
  // 若隐藏人物因此重新上锁，且当前正停留在其页面，则重绘并切回普通角色
  if(routes[activeRoute].hidden && !isHiddenUnlocked()) renderRoute();
  else renderTabs();
}

function updateRouteProgress(){
  const total = routes.length;
  const done = doneSet.size;
  const pct = Math.round(done/total*100);
  document.getElementById('routeFill').style.width = pct + '%';
  document.getElementById('routeText').textContent = `${done} / ${total} 路线`;
  document.getElementById('routePct').textContent = pct + '%';
}
updateRouteProgress();
renderRoute();

/* ================= 游戏时长进度条 ================= */
const timePlayedEl = document.getElementById('timePlayed');
const timeGoalEl = document.getElementById('timeGoal');
timePlayedEl.value = localStorage.getItem('bh_time_played') || '';
timeGoalEl.value = localStorage.getItem('bh_time_goal') || 50;

function updateTimeProgress(){
  const played = parseFloat(timePlayedEl.value) || 0;
  const goal = parseFloat(timeGoalEl.value) || 50;
  const pct = Math.min(100, Math.round(played/goal*100));
  document.getElementById('timeFill').style.width = pct + '%';
  document.getElementById('timeText').textContent = `${played}h / ${goal}h`;
  document.getElementById('timePct').textContent = pct + '%';
  localStorage.setItem('bh_time_played', timePlayedEl.value);
  localStorage.setItem('bh_time_goal', timeGoalEl.value);
}
timePlayedEl.addEventListener('input', updateTimeProgress);
timeGoalEl.addEventListener('input', updateTimeProgress);
updateTimeProgress();

